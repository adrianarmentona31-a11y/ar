// Deep-merge extras into main translations bundle
export function mergeTranslations(base) {
  const out = {};
  for (const loc of Object.keys(base)) {
    out[loc] = { ...base[loc], ...(extraTranslations[loc] || {}) };
  }
  return out;
}
